export function resolveSpecialtyCode(value: string): string | null {
  if (!value) return null;
  if (value.startsWith('SPEC.')) return value;
  const direct = SPECIALTY_ALIAS_TO_CODE[value];
  if (direct) return direct;
  const lower = value.toLowerCase();
  for (const [alias, code] of Object.entries(SPECIALTY_ALIAS_TO_CODE)) {
    if (alias.toLowerCase() === lower) return code;
  }
  return null;
}
