import { useEffect, useState } from 'react';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import { toast } from '@/components/ui/sonner';
import { api } from '@/lib/api';

/**
 * File 14 §14.2 — print studio: template HTML/CSS editor, variable lint
 * feedback from the server, live preview in a sandboxed iframe, publish.
 * Plus a WYSIWYG letterhead builder (visual controls → generated HTML).
 */
const DOCTYPES = ['bill', 'token', 'label', 'wristband', 'discharge', 'prescription'];

const FONTS = ['Inter, sans-serif', 'Georgia, serif', "'Times New Roman', serif", "'Courier New', monospace", "'Trebuchet MS', sans-serif"];

function escapeHtml(s: string) {
  return String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c] as string));
}

function buildLetterheadHtml(lh: any, docType: string) {
  const esc = escapeHtml;
  const logo = lh.logoUrl
    ? `<img src="${esc(lh.logoUrl)}" alt="logo" style="height:56px;width:auto;object-fit:contain" onerror="this.style.display='none'">`
    : '';
  return `<div class="fm-letterhead">
  <header class="lh-header" style="border-color:${esc(lh.accent)}">
    ${logo}
    <div class="lh-id">
      <div class="lh-name" style="color:${esc(lh.accent)}">${esc(lh.hospitalName)}</div>
      ${lh.tagline ? `<div class="lh-tagline">${esc(lh.tagline)}</div>` : ''}
      <div class="lh-contact">${esc(lh.address)}${lh.phone ? ' · ' + esc(lh.phone) : ''}${lh.email ? ' · ' + esc(lh.email) : ''}</div>
      ${lh.regNo ? `<div class="lh-reg">Reg. No: ${esc(lh.regNo)}</div>` : ''}
    </div>
  </header>
  <div class="lh-body">
    <div class="lh-doctitle">${esc(docType.toUpperCase())}</div>
    <p class="lh-placeholder">Document content renders here — <code>{{variables}}</code> are filled at print time.</p>
  </div>
  <footer class="lh-footer" style="border-color:${esc(lh.accent)}">
    ${lh.footerNote ? `<span>${esc(lh.footerNote)}</span>` : ''}
    <span class="lh-page">Page 1 · Generated by FindMedi</span>
  </footer>
</div>`;
}

function letterheadCss(lh: any) {
  return `
.fm-letterhead { font-family: ${lh.font}; color: #111; display: flex; flex-direction: column; min-height: 96vh; }
.lh-header { display: flex; align-items: center; gap: 16px; padding-bottom: 10px; border-bottom: 3px solid ${lh.accent}; }
.lh-name { font-size: 22px; font-weight: 800; letter-spacing: .3px; }
.lh-tagline { font-size: 12px; color: #555; margin-top: 2px; }
.lh-contact { font-size: 11px; color: #444; margin-top: 4px; }
.lh-reg { font-size: 10px; color: #777; margin-top: 2px; }
.lh-body { flex: 1; padding: 18px 0; }
.lh-doctitle { font-size: 16px; font-weight: 700; color: ${lh.accent}; border-bottom: 1px dashed #ccc; padding-bottom: 6px; margin-bottom: 12px; }
.lh-placeholder { font-size: 12px; color: #666; }
.lh-footer { display: flex; justify-content: space-between; font-size: 10px; color: #666; border-top: 2px solid ${lh.accent}; padding-top: 6px; }
.lh-page { color: #999; }`.trim();
}

export default function PrintStudio() {
  const [templates, setTemplates] = useState<any[]>([]);
  const [docType, setDocType] = useState('bill');
  const [name, setName] = useState('');
  const [html, setHtml] = useState('<h1>{{hospital.name}}</h1><p>Total {{bill.amount}} ({{inWords bill.amount}})</p>');
  const [css, setCss] = useState('');
  const [tab, setTab] = useState<'html' | 'css'>('html');
  const [mode, setMode] = useState<'code' | 'letterhead'>('code');
  const [preview, setPreview] = useState('');
  const [lint, setLint] = useState<string[]>([]);

  // WYSIWYG letterhead state
  const [lh, setLh] = useState({
    hospitalName: 'FindMedi Multispeciality Hospital',
    tagline: 'Compassion · Care · Cure',
    address: 'Sector 44, Gurugram, Haryana 122003',
    phone: '+91 124 456 7890',
    email: 'care@findmedi.example',
    regNo: 'HR/HOSP/2026/0142',
    accent: '#0f766e',
    font: FONTS[0],
    logoUrl: '',
    footerNote: '24×7 Emergency · NABH Accredited',
  });

  const load = async () => {
    try {
      const r: any = await (api as any).getPrintTemplates({ docType });
      setTemplates(r?.templates || []);
    } catch { toast.error('Failed to load templates'); }
  };
  useEffect(() => { load(); }, [docType]);

  // Live letterhead preview (client-side compose; no server round trip)
  useEffect(() => {
    if (mode !== 'letterhead') return;
    const doc = `<!doctype html><html><head><meta charset="utf-8"><style>
      body { margin: 0; padding: 16px; background: #f5f5f5; }
      .page { background: #fff; padding: 24px; box-shadow: 0 1px 6px rgba(0,0,0,.15); }
      ${letterheadCss(lh)}
    </style></head><body><div class="page">${buildLetterheadHtml(lh, docType)}</div></body></html>`;
    setPreview(doc);
  }, [lh, docType, mode]);

  const applyLetterhead = () => {
    setHtml(buildLetterheadHtml(lh, docType));
    setCss(letterheadCss(lh));
    setMode('code');
    setTab('html');
    toast.success('Letterhead applied to editor — save to publish');
  };

  const save = async () => {
    try {
      await (api as any).createPrintTemplate({ docType, name: name || `${docType} template`, html, css });
      toast.success('Draft saved (publish from the list when reviewed)');
      setName('');
      load();
    } catch (err: any) {
      const unknown = err?.unknown || err?.response?.unknown;
      if (unknown) setLint(unknown);
      toast.error(err?.message || 'Save failed (unknown variables?)');
    }
  };

  const testRender = async () => {
    try {
      const sample: any = { hospital: { name: 'Demo Hospital' }, bill: { amount: 1250, invoiceId: 'INV-1', paid: 1250, balance: 0 }, token: { number: 'A-014', department: 'OPD' }, patient: { name: 'Demo Patient' } };
      const r: any = await (api as any).renderPrint({ docType, data: sample, entityRef: 'preview' });
      setPreview(r?.html || '');
      setLint([]);
    } catch (err: any) { toast.error(err?.message || 'Render failed'); }
  };

  const lhField = (key: keyof typeof lh, label: string, ph = '') => (
    <label className="block text-xs">
      <span className="text-muted-foreground">{label}</span>
      <Input className="h-8 text-xs mt-0.5" placeholder={ph} value={String(lh[key])} onChange={(e) => setLh({ ...lh, [key]: e.target.value })} />
    </label>
  );

  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-center gap-2">
        <h1 className="text-2xl font-heading font-bold mr-auto">Print Studio</h1>
        <div className="flex rounded-md border overflow-hidden" role="tablist" aria-label="Editor mode">
          <button
            role="tab" aria-selected={mode === 'code'}
            className={`px-3 h-9 text-sm ${mode === 'code' ? 'bg-primary text-primary-foreground' : 'bg-background'}`}
            onClick={() => setMode('code')}
          >Code</button>
          <button
            role="tab" aria-selected={mode === 'letterhead'}
            className={`px-3 h-9 text-sm ${mode === 'letterhead' ? 'bg-primary text-primary-foreground' : 'bg-background'}`}
            onClick={() => setMode('letterhead')}
          >Letterhead builder</button>
        </div>
        <select aria-label="Doc type" className="h-10 rounded-md border border-input bg-background px-3 text-sm" value={docType} onChange={(e) => setDocType(e.target.value)}>
          {DOCTYPES.map((d) => <option key={d} value={d}>{d}</option>)}
        </select>
        <Input className="w-56" placeholder="Template name" value={name} onChange={(e) => setName(e.target.value)} />
        <Button variant="outline" onClick={testRender}>Test render</Button>
        <Button onClick={save}>Save draft</Button>
      </div>
      {lint.length > 0 && <p className="text-sm text-destructive">Unknown variables: {lint.join(', ')} — registry me nahi hain.</p>}

      {mode === 'letterhead' ? (
        <div className="grid lg:grid-cols-[320px_1fr] gap-3">
          <Card>
            <CardHeader><CardTitle className="text-sm">Letterhead controls</CardTitle></CardHeader>
            <CardContent className="space-y-2.5 text-xs">
              {lhField('hospitalName', 'Hospital name')}
              {lhField('tagline', 'Tagline')}
              {lhField('address', 'Address')}
              <div className="grid grid-cols-2 gap-2">
                {lhField('phone', 'Phone')}
                {lhField('email', 'Email')}
              </div>
              {lhField('regNo', 'Registration no.')}
              {lhField('logoUrl', 'Logo URL (optional)', 'https://…/logo.png')}
              {lhField('footerNote', 'Footer note')}
              <div className="grid grid-cols-2 gap-2">
                <label className="block text-xs">
                  <span className="text-muted-foreground">Accent color</span>
                  <div className="flex items-center gap-2 mt-0.5">
                    <input type="color" aria-label="Accent color" value={lh.accent} onChange={(e) => setLh({ ...lh, accent: e.target.value })} className="h-8 w-10 rounded border bg-background p-0.5" />
                    <Input className="h-8 text-xs font-mono" value={lh.accent} onChange={(e) => setLh({ ...lh, accent: e.target.value })} />
                  </div>
                </label>
                <label className="block text-xs">
                  <span className="text-muted-foreground">Font</span>
                  <select className="w-full h-8 mt-0.5 rounded-md border border-input bg-background px-2 text-xs" value={lh.font} onChange={(e) => setLh({ ...lh, font: e.target.value })}>
                    {FONTS.map((f) => <option key={f} value={f}>{f.split(',')[0].replace(/'/g, '')}</option>)}
                  </select>
                </label>
              </div>
              <div className="flex gap-2 pt-1">
                <Button size="sm" onClick={applyLetterhead}>Apply to editor</Button>
                <Button size="sm" variant="outline" onClick={testRender}>Server render</Button>
              </div>
            </CardContent>
          </Card>
          <Card>
            <CardHeader><CardTitle className="text-sm">WYSIWYG preview — A4 ({docType})</CardTitle></CardHeader>
            <CardContent>
              <iframe title="letterhead preview" sandbox="" srcDoc={preview} className="w-full h-[640px] rounded-md border bg-white" />
            </CardContent>
          </Card>
        </div>
      ) : (
        <div className="grid lg:grid-cols-2 gap-3">
          <Card>
            <CardHeader>
              <div className="flex gap-1">
                {(['html', 'css'] as const).map((t) => (
                  <Button key={t} size="sm" variant={tab === t ? 'default' : 'outline'} onClick={() => setTab(t)}>{t.toUpperCase()}</Button>
                ))}
              </div>
            </CardHeader>
            <CardContent>
              <textarea
                aria-label={`${tab} editor`}
                className="w-full h-96 rounded-md border border-input bg-background p-3 font-mono text-xs"
                value={tab === 'html' ? html : css}
                onChange={(e) => (tab === 'html' ? setHtml(e.target.value) : setCss(e.target.value))}
                spellCheck={false}
              />
            </CardContent>
          </Card>
          <Card>
            <CardHeader><CardTitle className="text-sm">Live preview (sandboxed)</CardTitle></CardHeader>
            <CardContent>
              <iframe title="print preview" sandbox="" srcDoc={preview} className="w-full h-96 rounded-md border bg-white" />
            </CardContent>
          </Card>
        </div>
      )}

      <Card>
        <CardHeader><CardTitle className="text-sm">Versions ({templates.length})</CardTitle></CardHeader>
        <CardContent className="space-y-1 text-sm">
          {templates.slice(0, 10).map((t: any) => (
            <p key={t._id} className="flex justify-between"><span>{t.name} · v{t.version}</span><span className="text-muted-foreground">{t.status}</span></p>
          ))}
        </CardContent>
      </Card>
    </div>
  );
}
