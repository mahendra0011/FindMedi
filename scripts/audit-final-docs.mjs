#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const docsRoot = path.join(root, 'FindMedi-Final-Docs');
const tracker = path.join(docsRoot, '00-Reference', 'FindMedi-Open-Items.md');
const write = process.argv.includes('--write');
const failOnOpen = process.argv.includes('--require-clear');

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(full);
    return entry.isFile() && entry.name.toLowerCase().endsWith('.md') ? [full] : [];
  });
}

const files = walk(docsRoot).sort();
const open = [];
let checked = 0;
let total = 0;
for (const file of files) {
  const lines = fs.readFileSync(file, 'utf8').replace(/^\uFEFF/, '').split(/\r?\n/);
  for (let i = 0; i < lines.length; i += 1) {
    const match = lines[i].match(/^\s*-\s*\[([ xX])\]\s*(.*)$/);
    if (!match) continue;
    total += 1;
    if (match[1].toLowerCase() === 'x') checked += 1;
    else {
      const relative = path.relative(docsRoot, file).replaceAll(path.sep, '/');
      open.push(`- [${relative}:${i + 1}] ${match[2].trim()}`);
    }
  }
}

const date = new Intl.DateTimeFormat('en-CA', {
  timeZone: 'Asia/Kolkata', year: 'numeric', month: '2-digit', day: '2-digit',
}).format(new Date());
console.log(`Files: ${files.length}; checklist: ${checked}/${total} checked; ${open.length} open.`);

if (write) {
  let content = fs.readFileSync(tracker, 'utf8').replace(/^\uFEFF/, '');
  content = content.replace(/Current state \(re-audited [^)]+\): \d+ checked, \d+ unchecked\./,
    `Current state (re-audited ${date}): ${checked} checked, ${open.length} unchecked.`);
  content = content.replace(/\(\d+ files, \d+ checklist items\)/,
    `(${files.length} files, ${total} checklist items)`);
  content = content.replace(/Live audit: \d+ checked, \d+ unchecked\./,
    `Live audit: ${checked} checked, ${open.length} unchecked.`);
  content = content.replace(/The following \d+ entries are the exact unchecked checklist lines found in `FindMedi-Final-Docs\/\*\*\/\*\.md` during the [^:]+ audit\./,
    `The following ${open.length} entries are the exact unchecked checklist lines found in \`FindMedi-Final-Docs/**/*.md\` during the ${date} audit.`);
  const marker = '## Exhaustive live checklist inventory (source of truth)';
  const markerIndex = content.indexOf(marker);
  if (markerIndex < 0) throw new Error(`Tracker section not found: ${marker}`);
  const section = `${marker}\n\nThis section is generated by \`node scripts/audit-final-docs.mjs --write\`. It includes every open checkbox with its current source line. The preceding numbered register is a prioritised summary; use this inventory as the exact count. Do not close a checkbox without its required proof and approval.\n\n${open.join('\n')}\n`;
  content = `${content.slice(0, markerIndex)}${section}`;
  fs.writeFileSync(tracker, content, 'utf8');
  console.log(`Updated ${path.relative(root, tracker)}.`);
}

if (failOnOpen && open.length > 0) process.exitCode = 1;
